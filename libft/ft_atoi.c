#include "libft.h"

int	ft_atoi(const char *str)
{
	int	i;
	int	nbr;
	int	less_counter;

	i = 0;
	nbr = 0;
	less_counter = 0;
	while (str[i] && (str[i] == ' ' || (str[i] >= 9 && str[i] <= 13)))
		i++;
	if (str[i] && (str[i] == '+' || str[i] == '-'))
	{
		if (str[i] == '-')
			less_counter++;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		nbr = nbr * 10 + (str[i] - 48);
		i++;
	}
	if (less_counter % 2 == 1)
		nbr = nbr * -1;
	return (nbr);
}
